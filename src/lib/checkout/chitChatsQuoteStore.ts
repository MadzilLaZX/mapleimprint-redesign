import { createHash, randomUUID } from "node:crypto";
import type { SupabaseClient } from "@supabase/supabase-js";
import type { ShippingAddressInput, ShippingOption } from "./shippingProvider";
import type { ChitChatsPackageInput } from "./chitChatsShippingProvider.ts";
import { buildChitChatsRateCacheKey } from "./chitChatsRateCache.ts";

// Cross-serverless-instance coordination layer underneath chitChatsRateCache.ts's in-process
// cache. See that file's header for why deduplication matters at all (Chit Chats has no
// quote-only endpoint, so every cache miss is a real shipment creation). This file provides the
// low-level, token-based compare-and-swap primitives; chitChatsQuoteCoordinator.ts is where the
// actual wait/retry/reconciliation ALGORITHM built on top of them lives -- kept separate so this
// file stays a thin, testable data-access layer and the coordinator's distributed-coordination
// logic can be reasoned about (and tested) on its own.
//
// OWNERSHIP MODEL: every 'pending' claim carries an `ownerToken` (a random UUID generated by the
// claiming request) and a short `leaseExpiresAt`. Every mutating operation on a row this store
// exposes (fill, release, takeOver) is a conditional UPDATE/DELETE that ALSO matches on the
// current ownerToken (and, for takeOver, the row's current status/expiry) -- this is the
// compare-and-swap that makes it safe for two requests to coordinate over the SAME row without a
// held database lock or transaction spanning the external Chit Chats call (which this store never
// does -- every method here is a single fast statement). A worker whose lease has already expired
// and been taken over by someone else will have its own fill()/release() calls silently rejected
// (return false / affect zero rows) rather than corrupting a newer result.

export const QUOTE_PERSIST_TTL_MS = 10 * 60 * 1000; // full quote freshness window -- app policy
export const DEFAULT_LEASE_DURATION_MS = 30 * 1000; // how long a claim is trusted before being considered possibly-abandoned

export interface ChitChatsPersistedQuoteKey {
  address: ShippingAddressInput;
  subtotalCents: number;
  pkg: ChitChatsPackageInput;
}

export interface ChitChatsPersistedQuote {
  fingerprint: string;
  status: "pending" | "ready";
  ownerToken: string;
  chitChatsShipmentId: string | null;
  rates: ShippingOption[] | null;
  purchasedAt: Date | null;
  expiresAt: Date;
  leaseExpiresAt: Date;
}

export type ChitChatsClaimOutcome =
  /** This call's claim won -- caller now owns the fingerprint and is responsible for calling the
   *  real rate fetcher, then fill() (on success) or release() (on failure). */
  | { kind: "owner"; ownerToken: string }
  /** A fresh, non-expired, filled-in quote already exists -- reuse it, no external call needed. */
  | { kind: "ready"; quote: ChitChatsPersistedQuote }
  /** Another request currently holds a LIVE lease (hasn't expired yet) -- the caller should wait
   *  (bounded) and re-inspect, never call the external fetcher itself in this state. */
  | { kind: "wait"; leaseExpiresAt: Date }
  /** The existing row is either a 'pending' claim whose lease has expired (the owner may have
   *  crashed -- OR may have actually succeeded and just failed to report back), or a 'ready' quote
   *  whose freshness window has simply expired (ordinary cache expiry, no crash ambiguity). Either
   *  way, recovery requires calling takeOver() -- never a direct external call -- and, for the
   *  'pending'-lease-expired case specifically, reconciliation BEFORE that takeover is used to
   *  create anything new (see chitChatsQuoteCoordinator.ts's header for why). `wasPending`
   *  distinguishes the two so the coordinator knows whether reconciliation is actually needed. */
  | { kind: "stale"; priorOwnerToken: string; wasPending: boolean };

export interface ChitChatsQuoteStore {
  /** Attempts to claim a fingerprint for a NEW quote request (inserting a 'pending' placeholder
   *  with `newOwnerToken`), or inspects the existing row if one is already there. Never performs
   *  or waits on any external call itself -- returns immediately either way. */
  claimOrInspect(
    key: ChitChatsPersistedQuoteKey,
    fingerprint: string,
    now: Date,
    newOwnerToken: string,
    quoteExpiresAt: Date,
    leaseExpiresAt: Date,
  ): Promise<ChitChatsClaimOutcome>;

  /** Resets a STALE row (status='stale' per claimOrInspect's own judgement) to a fresh 'pending'
   *  claim under `newOwnerToken`, but ONLY if the row is still owned by `expectedPriorOwnerToken`
   *  AND still in the exact stale state observed -- a true compare-and-swap, so a worker recovering
   *  from what it believes is a crashed/expired claim can never clobber a result that arrived in
   *  the meantime (from the original owner finishing late, or another recoverer winning first).
   *  Returns false (never throws) if the CAS didn't apply -- the caller should re-run
   *  claimOrInspect and react to whatever the row's current state turns out to be. */
  takeOver(
    fingerprint: string,
    expectedPriorOwnerToken: string,
    newOwnerToken: string,
    now: Date,
    quoteExpiresAt: Date,
    leaseExpiresAt: Date,
  ): Promise<boolean>;

  /** Fills a 'pending' row with a successful rate result, transitioning it to 'ready' -- only if
   *  still owned by `ownerToken`. Returns false if the CAS didn't apply (lease was taken over by
   *  someone else before this call landed) -- the caller still got a real answer from Chit Chats
   *  in that case, it just couldn't persist it for others to reuse; see the coordinator for how
   *  that's handled. */
  fill(fingerprint: string, ownerToken: string, rates: ShippingOption[], chitChatsShipmentId: string | null): Promise<boolean>;

  /** Removes a 'pending' row -- called when the real rate fetch FAILS, so a transient outage
   *  doesn't leave a stuck claim blocking every future request until its lease naturally expires.
   *  Only applies if still owned by `ownerToken`; returns false otherwise (harmless -- it means
   *  someone else already took over, so there's nothing of this caller's left to release). */
  release(fingerprint: string, ownerToken: string): Promise<boolean>;

  /** Returns a non-expired, 'ready' row for this fingerprint, or null (not found, still pending,
   *  or expired). Never returns an expired row. */
  findReady(fingerprint: string, now: Date): Promise<ChitChatsPersistedQuote | null>;

  /** Marks a quote's shipment as purchased -- a future, separate, explicitly-authorized step (see
   *  chitChatsPostagePurchase.ts) calls this after a real PATCH /shipments/{id}/buy succeeds, so
   *  cleanup (deleteExpiredUnpurchased) can never remove it afterward. */
  markPurchased(fingerprint: string, now: Date): Promise<void>;

  /** Deletes expired, NEVER-purchased, NOT-actively-leased rows. The leaseExpiresAt condition
   *  exists so cleanup can never race an actively in-flight claim even in the (shouldn't-happen)
   *  case its quote-level expiresAt has already passed. Returns the count removed. */
  deleteExpiredUnpurchased(now: Date): Promise<number>;
}

/** SHA-256 of the same normalized fields chitChatsRateCache.ts's in-memory key already uses --
 *  hashed purely so the database column is a short, fixed-length, index-friendly value; it
 *  carries no secrecy requirement of its own, so a cryptographic hash is used here for its
 *  collision-resistance property, not for concealment. */
export function buildQuoteFingerprint(key: ChitChatsPersistedQuoteKey): string {
  return createHash("sha256").update(buildChitChatsRateCacheKey(key)).digest("hex");
}

/** A fresh, unguessable token identifying one claim attempt -- exported so the coordinator (and
 *  tests) can generate one without reaching into node:crypto directly. */
export function generateOwnerToken(): string {
  return randomUUID();
}

function isReady(expiresAt: Date, now: Date): boolean {
  return expiresAt.getTime() > now.getTime();
}

/** Real implementation, backed by the ChitChatsShippingQuote table -- NOT reachable from any live
 *  code path today (no caller constructs this against a real Supabase project this round; the
 *  table it targets hasn't been created, since the migration above hasn't been applied). Exists so
 *  activating persistence is a configuration/wiring change once the migration is approved, not
 *  something built from scratch under launch pressure later. */
export class SupabaseChitChatsQuoteStore implements ChitChatsQuoteStore {
  // Not a TS parameter-property -- plain `node --test`'s strip-only mode can't parse that syntax,
  // and this file's own test needs to run under it directly.
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  private readonly supabaseAdmin: SupabaseClient<any, any, any>;

  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  constructor(supabaseAdmin: SupabaseClient<any, any, any>) {
    this.supabaseAdmin = supabaseAdmin;
  }

  private rowToQuote(fingerprint: string, row: {
    status: "pending" | "ready";
    ownerToken: string;
    chitChatsShipmentId: string | null;
    rates: ShippingOption[] | null;
    purchasedAt: string | null;
    expiresAt: string;
    leaseExpiresAt: string;
  }): ChitChatsPersistedQuote {
    return {
      fingerprint,
      status: row.status,
      ownerToken: row.ownerToken,
      chitChatsShipmentId: row.chitChatsShipmentId,
      rates: row.rates,
      purchasedAt: row.purchasedAt ? new Date(row.purchasedAt) : null,
      expiresAt: new Date(row.expiresAt),
      leaseExpiresAt: new Date(row.leaseExpiresAt),
    };
  }

  async claimOrInspect(
    key: ChitChatsPersistedQuoteKey,
    fingerprint: string,
    now: Date,
    newOwnerToken: string,
    quoteExpiresAt: Date,
    leaseExpiresAt: Date,
  ): Promise<ChitChatsClaimOutcome> {
    // Bounded retry (not unbounded recursion) for the vanishingly rare case the row is deleted
    // (e.g. a genuine race with cleanup) between our failed insert and the follow-up read below.
    for (let attempt = 0; attempt < 3; attempt++) {
      const { data: inserted } = await this.supabaseAdmin
        .from("ChitChatsShippingQuote")
        .upsert(
          {
            quoteFingerprint: fingerprint,
            status: "pending",
            ownerToken: newOwnerToken,
            leaseExpiresAt: leaseExpiresAt.toISOString(),
            destinationAddress: key.address,
            parcel: key.pkg,
            subtotalCents: key.subtotalCents,
            expiresAt: quoteExpiresAt.toISOString(),
          },
          { onConflict: "quoteFingerprint", ignoreDuplicates: true },
        )
        .select("quoteFingerprint")
        .maybeSingle();

      if (inserted) return { kind: "owner", ownerToken: newOwnerToken };

      const { data: row } = await this.supabaseAdmin
        .from("ChitChatsShippingQuote")
        .select("status, ownerToken, leaseExpiresAt, chitChatsShipmentId, rates, purchasedAt, expiresAt")
        .eq("quoteFingerprint", fingerprint)
        .maybeSingle();

      if (!row) continue; // vanished between our failed insert and this read -- retry the insert

      if (row.status === "ready") {
        if (isReady(new Date(row.expiresAt), now)) {
          return { kind: "ready", quote: this.rowToQuote(fingerprint, row) };
        }
        return { kind: "stale", priorOwnerToken: row.ownerToken, wasPending: false };
      }
      // pending
      if (new Date(row.leaseExpiresAt).getTime() > now.getTime()) {
        return { kind: "wait", leaseExpiresAt: new Date(row.leaseExpiresAt) };
      }
      return { kind: "stale", priorOwnerToken: row.ownerToken, wasPending: true };
    }
    // Exhausted retries -- treat as "wait a moment and try the whole thing again" rather than
    // throwing from deep inside the data-access layer.
    return { kind: "wait", leaseExpiresAt: new Date(now.getTime() + 1000) };
  }

  async takeOver(
    fingerprint: string,
    expectedPriorOwnerToken: string,
    newOwnerToken: string,
    now: Date,
    quoteExpiresAt: Date,
    leaseExpiresAt: Date,
  ): Promise<boolean> {
    const patch = {
      status: "pending" as const,
      ownerToken: newOwnerToken,
      leaseExpiresAt: leaseExpiresAt.toISOString(),
      expiresAt: quoteExpiresAt.toISOString(),
      rates: null,
      chitChatsShipmentId: null,
      updatedAt: now.toISOString(),
    };
    // Two separate, simple conditional UPDATEs rather than one query with a nested OR/AND filter
    // -- the exact PostgREST `.or()`/`.and()` grouping syntax for this specific compound condition
    // hasn't been verified against a live project this round (no credentials), so this uses only
    // plain `.eq()`/`.lte()` chains that are unambiguously supported, at the cost of a second
    // round-trip on the less-common branch. Either one succeeding is the CAS: a row changing state
    // between our claimOrInspect() read and this call (the stale owner finishing late, or another
    // recoverer already winning) means BOTH conditions fail to match, and this correctly returns
    // false rather than clobbering that newer state.
    const pendingTakeover = await this.supabaseAdmin
      .from("ChitChatsShippingQuote")
      .update(patch)
      .eq("quoteFingerprint", fingerprint)
      .eq("ownerToken", expectedPriorOwnerToken)
      .eq("status", "pending")
      .lte("leaseExpiresAt", now.toISOString())
      .select("quoteFingerprint")
      .maybeSingle();
    if (pendingTakeover.data) return true;

    const readyTakeover = await this.supabaseAdmin
      .from("ChitChatsShippingQuote")
      .update(patch)
      .eq("quoteFingerprint", fingerprint)
      .eq("ownerToken", expectedPriorOwnerToken)
      .eq("status", "ready")
      .lte("expiresAt", now.toISOString())
      .select("quoteFingerprint")
      .maybeSingle();
    return Boolean(readyTakeover.data);
  }

  async fill(fingerprint: string, ownerToken: string, rates: ShippingOption[], chitChatsShipmentId: string | null): Promise<boolean> {
    const { data } = await this.supabaseAdmin
      .from("ChitChatsShippingQuote")
      .update({ status: "ready", rates, chitChatsShipmentId, updatedAt: new Date().toISOString() })
      .eq("quoteFingerprint", fingerprint)
      .eq("ownerToken", ownerToken)
      .eq("status", "pending")
      .select("quoteFingerprint")
      .maybeSingle();
    return Boolean(data);
  }

  async release(fingerprint: string, ownerToken: string): Promise<boolean> {
    const { data } = await this.supabaseAdmin
      .from("ChitChatsShippingQuote")
      .delete()
      .eq("quoteFingerprint", fingerprint)
      .eq("ownerToken", ownerToken)
      .eq("status", "pending")
      .is("purchasedAt", null)
      .select("quoteFingerprint")
      .maybeSingle();
    return Boolean(data);
  }

  async findReady(fingerprint: string, now: Date): Promise<ChitChatsPersistedQuote | null> {
    const { data } = await this.supabaseAdmin
      .from("ChitChatsShippingQuote")
      .select("status, ownerToken, chitChatsShipmentId, rates, purchasedAt, expiresAt, leaseExpiresAt")
      .eq("quoteFingerprint", fingerprint)
      .eq("status", "ready")
      .gt("expiresAt", now.toISOString())
      .maybeSingle();
    if (!data) return null;
    return this.rowToQuote(fingerprint, data);
  }

  async markPurchased(fingerprint: string, now: Date): Promise<void> {
    await this.supabaseAdmin
      .from("ChitChatsShippingQuote")
      .update({ purchasedAt: now.toISOString() })
      .eq("quoteFingerprint", fingerprint);
  }

  async deleteExpiredUnpurchased(now: Date): Promise<number> {
    const { count } = await this.supabaseAdmin
      .from("ChitChatsShippingQuote")
      .delete({ count: "exact" })
      .lt("expiresAt", now.toISOString())
      .is("purchasedAt", null)
      .lt("leaseExpiresAt", now.toISOString());
    return count ?? 0;
  }
}

/** In-memory fake implementing the exact same narrow interface -- NOT a mock of Supabase's wire
 *  protocol (this codebase's established pattern for DB-dependent logic, see
 *  fulfillOrder.integration.test.ts, is a real Supabase integration test gated behind an explicit
 *  opt-in env var, not a fake client). This fake exists so the coordination algorithm --
 *  claim/wait/takeover/fill/release/expiry/purchased-protection -- is fully unit-testable, fast
 *  and deterministic, without a live database, while chitChatsQuoteStore.integration.test.ts
 *  covers the real SQL/constraint behavior separately (skipped by default, same as that file).
 *  Every mutating method here enforces the IDENTICAL token/status preconditions the real CAS
 *  UPDATE statements do, so a test exercising this fake is exercising the real concurrency
 *  contract, not a simplified approximation of it. */
export class InMemoryChitChatsQuoteStore implements ChitChatsQuoteStore {
  private readonly rows = new Map<string, ChitChatsPersistedQuote>();

  async claimOrInspect(
    _key: ChitChatsPersistedQuoteKey,
    fingerprint: string,
    now: Date,
    newOwnerToken: string,
    quoteExpiresAt: Date,
    leaseExpiresAt: Date,
  ): Promise<ChitChatsClaimOutcome> {
    const existing = this.rows.get(fingerprint);
    if (!existing) {
      this.rows.set(fingerprint, {
        fingerprint,
        status: "pending",
        ownerToken: newOwnerToken,
        chitChatsShipmentId: null,
        rates: null,
        purchasedAt: null,
        expiresAt: quoteExpiresAt,
        leaseExpiresAt,
      });
      return { kind: "owner", ownerToken: newOwnerToken };
    }
    if (existing.status === "ready") {
      if (isReady(existing.expiresAt, now)) return { kind: "ready", quote: existing };
      return { kind: "stale", priorOwnerToken: existing.ownerToken, wasPending: false };
    }
    if (existing.leaseExpiresAt.getTime() > now.getTime()) {
      return { kind: "wait", leaseExpiresAt: existing.leaseExpiresAt };
    }
    return { kind: "stale", priorOwnerToken: existing.ownerToken, wasPending: true };
  }

  async takeOver(
    fingerprint: string,
    expectedPriorOwnerToken: string,
    newOwnerToken: string,
    now: Date,
    quoteExpiresAt: Date,
    leaseExpiresAt: Date,
  ): Promise<boolean> {
    const row = this.rows.get(fingerprint);
    if (!row || row.ownerToken !== expectedPriorOwnerToken) return false;
    const stillStalePending = row.status === "pending" && row.leaseExpiresAt.getTime() <= now.getTime();
    const stillStaleReady = row.status === "ready" && row.expiresAt.getTime() <= now.getTime();
    if (!stillStalePending && !stillStaleReady) return false;
    this.rows.set(fingerprint, {
      ...row,
      status: "pending",
      ownerToken: newOwnerToken,
      leaseExpiresAt,
      expiresAt: quoteExpiresAt,
      rates: null,
      chitChatsShipmentId: null,
    });
    return true;
  }

  async fill(fingerprint: string, ownerToken: string, rates: ShippingOption[], chitChatsShipmentId: string | null): Promise<boolean> {
    const row = this.rows.get(fingerprint);
    if (!row || row.ownerToken !== ownerToken || row.status !== "pending") return false;
    this.rows.set(fingerprint, { ...row, status: "ready", rates, chitChatsShipmentId });
    return true;
  }

  async release(fingerprint: string, ownerToken: string): Promise<boolean> {
    const row = this.rows.get(fingerprint);
    if (!row || row.ownerToken !== ownerToken || row.status !== "pending" || row.purchasedAt) return false;
    this.rows.delete(fingerprint);
    return true;
  }

  async findReady(fingerprint: string, now: Date): Promise<ChitChatsPersistedQuote | null> {
    const row = this.rows.get(fingerprint);
    if (!row || row.status !== "ready") return null;
    if (!isReady(row.expiresAt, now)) return null;
    return row;
  }

  async markPurchased(fingerprint: string, now: Date): Promise<void> {
    const row = this.rows.get(fingerprint);
    if (!row) return;
    this.rows.set(fingerprint, { ...row, purchasedAt: now });
  }

  async deleteExpiredUnpurchased(now: Date): Promise<number> {
    let removed = 0;
    for (const [fingerprint, row] of this.rows) {
      if (row.purchasedAt) continue;
      if (row.leaseExpiresAt.getTime() >= now.getTime()) continue; // never race an active lease
      if (row.expiresAt.getTime() < now.getTime()) {
        this.rows.delete(fingerprint);
        removed++;
      }
    }
    return removed;
  }

  // Test/diagnostic only.
  size(): number {
    return this.rows.size;
  }

  // Test/diagnostic only -- lets a test inspect a row's current owner token directly, e.g. to
  // assert a stale worker's late fill()/release() call is rejected after a real takeover.
  peek(fingerprint: string): ChitChatsPersistedQuote | undefined {
    return this.rows.get(fingerprint);
  }
}
